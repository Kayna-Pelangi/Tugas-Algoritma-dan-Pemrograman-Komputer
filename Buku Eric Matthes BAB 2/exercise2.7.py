name = "\t\n Kayna Pelangi Maulana \n\t"

print("--- 1. Tampilan asli ---")
print(name)

print("--- 2. Hapus spasi kiri ---")
name = name.lstrip()
print(name)

print("--- 3. Hapus spasi kanan ---")
name = name.rstrip()
print(name)

print("--- 4. Hapus semua spasi luar ---")
name = name.strip()
print(name)